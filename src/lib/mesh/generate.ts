// Synthetic model files for browser mode (mock backend) and tests: a height-field STL,
// the same surface as OBJ, and a small 3MF cube. Deterministic for a given seed.
import { zipSync, strToU8 } from 'fflate';

function heightField(n: number, seed: number) {
  const size = 120, step = size / n;
  const h = (x: number, y: number) => 6 * Math.sin(x * 0.12 + seed) * Math.cos(y * 0.12) + 2 * Math.sin(x * 0.5 + y * 0.3 + seed) + Math.cos(y * 0.9);
  const tris: number[][][] = [];
  for (let j = 0; j < n; j++) for (let i = 0; i < n; i++) {
    const x0 = i * step - size / 2, x1 = x0 + step, y0 = j * step - size / 2, y1 = y0 + step;
    const p00 = [x0, y0, h(x0, y0)], p10 = [x1, y0, h(x1, y0)], p01 = [x0, y1, h(x0, y1)], p11 = [x1, y1, h(x1, y1)];
    tris.push([p00, p10, p11], [p00, p11, p01]);
  }
  return tris;
}

export function generateStl(triangles: number, seed = 0): ArrayBuffer {
  const n = Math.ceil(Math.sqrt(Math.max(triangles, 2) / 2));
  const tris = heightField(n, seed);
  const buf = new ArrayBuffer(84 + tris.length * 50);
  const view = new DataView(buf);
  view.setUint32(80, tris.length, true);
  let off = 84;
  for (const [a, b, c] of tris) {
    const u = [b![0]! - a![0]!, b![1]! - a![1]!, b![2]! - a![2]!], v = [c![0]! - a![0]!, c![1]! - a![1]!, c![2]! - a![2]!];
    const nn = [u[1]! * v[2]! - u[2]! * v[1]!, u[2]! * v[0]! - u[0]! * v[2]!, u[0]! * v[1]! - u[1]! * v[0]!];
    const len = Math.hypot(nn[0]!, nn[1]!, nn[2]!) || 1;
    for (const f of [nn[0]! / len, nn[1]! / len, nn[2]! / len, ...a!, ...b!, ...c!]) { view.setFloat32(off, f, true); off += 4; }
    off += 2;
  }
  return buf;
}

export function generateObj(triangles: number, seed = 0): ArrayBuffer {
  const n = Math.ceil(Math.sqrt(Math.max(triangles, 2) / 2));
  const tris = heightField(n, seed);
  const lines: string[] = ['# generated by Meshkeep mock'];
  let idx = 1;
  const faces: string[] = [];
  for (const t of tris) {
    for (const p of t) lines.push(`v ${p![0]!.toFixed(3)} ${p![1]!.toFixed(3)} ${p![2]!.toFixed(3)}`);
    faces.push(`f ${idx} ${idx + 1} ${idx + 2}`);
    idx += 3;
  }
  return new TextEncoder().encode(lines.concat(faces).join('\n') + '\n').buffer as ArrayBuffer;
}

